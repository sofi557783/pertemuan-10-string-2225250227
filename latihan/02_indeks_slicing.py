# Latihan 2: Indeks dan Slicing
# Input: Teks "Pemrograman"
# Proses: Akses karakter berdasarkan indeks positif, negatif, slicing, dan pembalikan string
# Output: Hasil karakter dan potongan teks sesuai indeks

teks = "Pemrograman"
print(teks[0])
print(teks[-1])
print(teks[:4])
print(teks[4:])
print(teks[::-1])